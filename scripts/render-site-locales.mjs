import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const site = new URL('../site/', import.meta.url);
const origin = 'https://covelet.future-element.com';
const locales = {
  'zh-CN': ['/', 'zh_CN'],
  en: ['/en/', 'en_US'],
  'zh-TW': ['/zh-tw/', 'zh_TW'],
  ja: ['/ja/', 'ja_JP'],
  ko: ['/ko/', 'ko_KR'],
  de: ['/de/', 'de_DE'],
  fr: ['/fr/', 'fr_FR'],
  ru: ['/ru/', 'ru_RU'],
};
const escapeHtml = (value) => value.replace(/[&<>"]/g, (character) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;',
})[character]);
const normalizeLineEndings = (value) => value.replace(/\r\n/g, '\n');
const template = normalizeLineEndings(readFileSync(new URL('index.html', site), 'utf8'));

function replaceAttribute(tag, attribute, value) {
  const pattern = new RegExp(`\\s${attribute}="[^"]*"`);
  if (!pattern.test(tag)) throw new Error(`Missing ${attribute} attribute in ${tag}`);
  return tag.replace(pattern, () => ` ${attribute}="${escapeHtml(value)}"`);
}

function renderLocale(locale, route, socialLocale) {
  const dictionary = JSON.parse(readFileSync(new URL(`i18n/${locale}.json`, site), 'utf8'));
  function message(key) {
    const value = dictionary[key];
    if (typeof value !== 'string' || !value.trim()) throw new Error(`Missing ${locale} translation for ${key}`);
    return value;
  }

  let html = template.replace(/<[a-z][\w-]*\b[^<>]*\bdata-i18n-(?:content|aria-label|href)="[^<>]*>/g, (tag) => {
    for (const [, attribute, key] of tag.matchAll(/\bdata-i18n-(content|aria-label|href)="([^"]+)"/g)) {
      tag = replaceAttribute(tag, attribute, message(key));
    }
    return tag;
  });
  let renderedTextBindings = 0;
  html = html.replace(/<([a-z][\w-]*)\b([^<>]*\bdata-i18n="([^"]+)"[^<>]*)>[^<]*<\/\1>/g,
    (_, tag, attributes, key) => {
      renderedTextBindings++;
      return `<${tag}${attributes}>${escapeHtml(message(key))}</${tag}>`;
    });
  if (renderedTextBindings !== [...template.matchAll(/\bdata-i18n="/g)].length) {
    throw new Error('Every data-i18n text binding must contain text only.');
  }

  return html
    .replace(/<!doctype html>/i, '$&\n<!-- Generated by scripts/render-site-locales.mjs. Edit site/index.html or the language dictionaries. -->')
    .replace(/^  <script type="application\/ld\+json" id="website-structured-data">[\s\S]*?<\/script>\n/m, '')
    .replace(/<html\b[^<>]*>/, (tag) => replaceAttribute(tag, 'lang', locale))
    .replace(/<link\b[^<>]*\brel="canonical"[^<>]*>/, (tag) => replaceAttribute(tag, 'href', origin + route))
    .replace(/<meta\b[^<>]*\bproperty="og:url"[^<>]*>/, (tag) => replaceAttribute(tag, 'content', origin + route))
    .replace(/<meta\b[^<>]*\bproperty="og:locale"[^<>]*>/, (tag) => replaceAttribute(tag, 'content', socialLocale))
    .replace(/<option\b[^<>]*\bvalue="([^"]+)"[^<>]*>/g, (tag, value) => {
      const option = tag.replace(/\s+selected(?:="[^"]*")?(?=\s|>)/, '');
      return value === locale ? option.replace(/>$/, ' selected>') : option;
    });
}

const alternateUrls = new Map([...template.matchAll(/<link rel="alternate" hreflang="([^"]+)" href="([^"]+)"/g)]
  .map(([, locale, url]) => [locale, url]));
for (const [locale, [route]] of [...Object.entries(locales), ['x-default', ['/']]]) {
  if (alternateUrls.get(locale) !== origin + route) throw new Error(`Missing or incorrect hreflang link for ${locale}`);
}

const outputs = new Map();
for (const [locale, [route, socialLocale]] of Object.entries(locales)) {
  if (route !== '/') outputs.set(`${route.slice(1)}index.html`, renderLocale(locale, route, socialLocale));
}
const urls = [...Object.values(locales).map(([route]) => route), '/privacy/'];
outputs.set('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map((route) => `  <url>\n    <loc>${origin}${route}</loc>\n  </url>`).join('\n')}
</urlset>
`);

if (process.argv.includes('--check')) {
  const stale = [];
  for (const [file, expected] of outputs) {
    try {
      if (normalizeLineEndings(readFileSync(new URL(file, site), 'utf8')) === expected) continue;
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    stale.push(`site/${file}`);
  }
  if (stale.length) {
    console.error(`Regenerate ${stale.join(', ')} with node scripts/render-site-locales.mjs`);
    process.exitCode = 1;
  }
} else {
  for (const [file, content] of outputs) {
    const target = new URL(file, site);
    mkdirSync(new URL('.', target), { recursive: true });
    writeFileSync(target, content);
  }
}
